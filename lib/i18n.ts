export const translate = (
  language: Language,
  key: TranslationKey,
  values?: TranslationValues,
) => {
  let text: string = language === 'ar' ? ar[key] : en[key];
  if (values) {
    for (const [name, value] of Object.entries(values)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
};
